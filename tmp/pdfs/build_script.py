doc=SimpleDocTemplate(str(out), pagesize=(595.28,841.89), rightMargin=48,leftMargin=48,topMargin=42,bottomMargin=55,title='CompletAI - Roteiro de apresentação do TCC',author='CompletAI')
doc.build(story,onFirstPage=footer,onLaterPages=footer)
