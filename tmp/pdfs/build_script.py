from pathlib import Path
from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer, PageBreak
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.lib.colors import HexColor
from reportlab.lib.enums import TA_LEFT

out = Path('output/pdf/roteiro-apresentacao-completai.pdf')
out.parent.mkdir(parents=True, exist_ok=True)
styles = getSampleStyleSheet()
styles.add(ParagraphStyle(name='TitleCustom', fontName='Helvetica-Bold', fontSize=24, leading=29, textColor=HexColor('#325DFB'), spaceAfter=12))
styles.add(ParagraphStyle(name='SectionCustom', fontName='Helvetica-Bold', fontSize=15, leading=19, spaceBefore=16, spaceAfter=10, textColor=HexColor('#1B1E28')))
styles.add(ParagraphStyle(name='Speech', fontName='Helvetica', fontSize=11, leading=16, spaceAfter=10, textColor=HexColor('#1B1E28')))
styles.add(ParagraphStyle(name='Cue', fontName='Helvetica-Oblique', fontSize=10, leading=14, spaceAfter=10, textColor=HexColor('#6B7280')))
story=[]
def p(text, style='Speech'): story.append(Paragraph(text, styles[style]))
def section(text): p(text,'SectionCustom')
def cue(text): p(text,'Cue')
p('CompletAI | Apresentação do TCC','TitleCustom')
cue('Roteiro de fala e demonstração • Duração estimada: 4 a 5 minutos')
section('1. Introdução técnica')
p('O CompletAI é um aplicativo desenvolvido em <b>Flutter</b>, utilizando a linguagem <b>Dart</b>, com foco principal na plataforma Android. O objetivo é auxiliar o motorista na comparação de postos de combustível, considerando preço, localização, horário de funcionamento e avaliações.')
p('O projeto utiliza o <b>Firebase Authentication</b> para autenticação e o <b>Cloud Firestore</b> para persistência dos dados.')
p('A organização do código segue a arquitetura <b>MVVM</b>, combinada com o <b>Repository Pattern</b>. Dessa forma, a interface fica na View, o estado e as ações são coordenados pelo ViewModel, e o acesso aos dados passa pelos Repositories e Services. O gerenciamento de estado e a injeção de dependências são realizados com <b>Riverpod</b>.')
section('2. Home do motorista')
cue('Demonstração: mostrar a tela inicial.')
p('Após a autenticação, o sistema identifica o papel da conta e direciona o motorista para esta home.')
p('A localização do dispositivo é utilizada para identificar a cidade e consultar os postos correspondentes. Nesta fase do projeto, o foco da descoberta é Bebedouro.')
p('Para tornar essa consulta consistente, utilizamos uma <b>chave normalizada de cidade</b>, chamada <b>citySearchKey</b>. Isso evita que diferenças de letras maiúsculas ou acentuação prejudiquem a busca.')
story.append(PageBreak())
p('Home e detalhes do posto','TitleCustom')
cue('Continuação da demonstração')
cue('Demonstração: mostrar a busca e alternar o combustível.')
p('O campo de pesquisa permite filtrar os postos por nome ou bairro. Esse filtro é executado localmente sobre os dados já carregados, evitando uma nova consulta ao banco a cada caractere digitado.')
p('O motorista pode selecionar gasolina, etanol ou diesel por toque ou gesto horizontal. A seleção atualiza a comparação dos preços e a ordenação da lista.')
p('Na ordenação por menor preço, a distância é utilizada como critério de desempate. Essa distância é calculada no próprio aplicativo, a partir das coordenadas do motorista e do posto.')
cue('Demonstração: abrir os filtros e destacar um cartão.')
p('Também temos filtros por avaliação, distância e funcionamento. O status “Aberto agora” é calculado com base nos horários cadastrados e considera situações em que o expediente atravessa a meia-noite.')
p('Os cartões apresentam as informações necessárias para uma comparação rápida: identificação do posto, bandeira, preços, distância, avaliação e atualização dos valores.')
p('A atualização manual é feita pelo gesto de puxar a lista para baixo, preservando as escolhas de busca e filtros.')
section('3. Detalhes do posto')
cue('Demonstração: tocar em um cartão.')
p('Ao selecionar um posto, o aplicativo abre uma tela de detalhes vinculada ao identificador daquele estabelecimento.')
p('Aqui, o motorista encontra a foto, os preços dos diferentes combustíveis, os serviços disponíveis e os horários de funcionamento.')
p('O botão “Como chegar” utiliza as coordenadas cadastradas para abrir uma rota externa no Google Maps, por meio do pacote <b>url_launcher</b>.')
cue('Demonstração: mostrar a foto e os serviços.')
p('Uma decisão importante para o desempenho foi separar a imagem dos dados principais do posto. A foto fica em um documento próprio e é carregada sob demanda, com reaproveitamento em memória. Assim, a consulta da listagem não precisa trazer todas as imagens junto com os preços.')
story.append(PageBreak())
p('Avaliações e arquitetura','TitleCustom')
section('4. Avaliações e favoritos')
cue('Demonstração: mostrar as ações de favorito e avaliação.')
p('O motorista pode salvar o posto como favorito. Esses registros ficam em uma subcoleção privada vinculada ao usuário, com acesso controlado pelas regras de segurança do Firestore.')
p('Na seção de avaliações, mostramos a nota média e uma prévia de até três comentários. A opção “Ver todas” abre uma lista paginada, evitando carregar todo o histórico de uma vez.')
p('Cada motorista pode manter uma avaliação por posto. Ao criar ou editar essa avaliação, o aplicativo atualiza o comentário e os campos de média e quantidade por meio de uma <b>transação do Firestore</b>. Isso permite executar essas alterações de forma atômica.')
cue('Demonstração: destacar a média.')
p('Por exemplo, avaliações de três e cinco estrelas resultam em média quatro. A escala permanece entre zero e cinco.')
p('A média e a quantidade são armazenadas como <b>dados agregados</b> no documento do posto. Essa estratégia evita consultar todas as avaliações sempre que precisamos exibir a nota na home.')
section('5. Arquitetura, estados e validação')
cue('Encerramento da apresentação.')
p('Nas duas telas, as Views não acessam o Firebase diretamente. Elas observam o estado disponibilizado pelos ViewModels, que utilizam <b>AsyncNotifier</b> e <b>AsyncValue</b> para representar carregamento, sucesso e erro.')
p('Essa separação facilita a manutenção e permite testar a lógica sem depender da interface. O projeto possui testes de ViewModel e de widgets, incluindo verificações de responsividade em telas pequenas.')
p('Também adotamos cuidados para operar dentro do plano gratuito do Firebase, como filtros locais, cache em memória, paginação e carregamento de imagens sob demanda.')
p('Com isso, o CompletAI reúne uma interface voltada à decisão do motorista e uma estrutura técnica que permite evoluir o aplicativo de forma organizada.')
def footer(canvas, doc):
    canvas.setStrokeColor(HexColor('#E3E6EC'))
    canvas.line(48,40,547,40)
    canvas.setFont('Helvetica',9)
    canvas.setFillColor(HexColor('#6B7280'))
